"""Literal rating boundaries plus v2's own applicability/date guards."""
from decimal import Decimal

import pytest

from test_farmer_model_v2 import env, reason
from due_app.calculations import reference_rating
from due_app.farmer_model_v2 import assess


@pytest.mark.parametrize('cutoff,below_rating,below_coefficient,at_rating,at_coefficient', [
    ('10', 'C', '0.3', 'CC', '0.3875'),
    ('20', 'CC', '0.3875', 'CCC', '0.475'),
    ('30', 'CCC', '0.475', 'B', '0.5625'),
    ('40', 'B', '0.5625', 'BB', '0.65'),
    ('50', 'BB', '0.65', 'BBB', '0.7375'),
    ('60', 'BBB', '0.7375', 'A', '0.825'),
    ('70', 'A', '0.825', 'AA', '0.9125'),
    ('80', 'AA', '0.9125', 'AAA', '1')])
@pytest.mark.parametrize('offset', ['-0.0001', '0', '0.0001'])
def test_exact_literal_rating_threshold_and_both_sides(cutoff, below_rating, below_coefficient, at_rating, at_coefficient, offset):
    # Expected bands/coefficients above are literals, not generated by the
    # production rules. The helper is the same one used by assess after clipping.
    result = reference_rating(str(Decimal(cutoff)+Decimal(offset)))
    expected = (below_rating, below_coefficient) if Decimal(offset) < 0 else (at_rating, at_coefficient)
    assert result['state'] == 'reference_only'
    assert (result['rating'], result['coefficient']) == expected


@pytest.mark.parametrize('score,rating,coefficient', [('0', 'C', '0.3'), ('100', 'AAA', '1')])
def test_clipped_total_score_endpoints_keep_exact_original_coefficient(score, rating, coefficient):
    result = reference_rating(score)
    assert (result['rating'], result['coefficient']) == (rating, coefficient)


@pytest.mark.parametrize('subject_type,product_id', [('company', 'farmer_demo'), ('farmer', 'different_product')])
def test_v2_own_http_model_applicability_rejects_wrong_subject_or_product(env, subject_type, product_id):
    cid = env.store.create_case('V2 wrong synthetic applicability', subject_type, product_id)['id']
    prefix = f'/api/due-diligence/cases/{cid}/calculation/v2'
    for suffix in ('', '/examples'):
        response = env.client.get(prefix+suffix)
        assert response.status_code == 409
        assert response.json()['detail']['code'] == 'model_not_applicable'
    response = env.client.post(prefix+'/run', json={'expected_revision': 1})
    assert response.status_code == 409
    assert response.json()['detail']['code'] == 'model_not_applicable'


def test_v2_baseline_must_equal_current_case_snapshot_date(env):
    env.raw['evaluation_as_of'] = '2026-10-29'
    # Keep every as-of input internally consistent with the wrong requested
    # date, so rejection specifically retains the current-case baseline guard.
    for record in list(env.raw['fields'].values())+[e['amount'] for e in env.raw['assets']+env.raw['debts']]:
        if record['period']['kind'] == 'as_of':
            record['period'].update(start='2026-10-29', end='2026-10-29')
    result = assess(env.raw, env.diligence.workspace(env.cid))
    assert result['state'] == 'blocked' and result['effective_limit'] is None
    assert reason(result, 'baseline_not_current')


def test_v2_partial_accounting_year_is_not_annualized(env):
    env.raw['accounting_period']['start'] = '2025-02-01'
    for record in env.raw['fields'].values():
        if record['period']['kind'] == 'year':
            record['period']['start'] = '2025-02-01'
    result = assess(env.raw, env.diligence.workspace(env.cid))
    assert result['state'] == 'blocked' and result['effective_limit'] is None
    assert reason(result, 'complete_accounting_year_required')
